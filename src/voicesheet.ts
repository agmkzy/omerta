// Menu entries that reuse a code but mean something else
const OVERRIDE: Record<string, Say> = {
  'earn|Discuss what’s owed': { _: `About the money between us` },
  'earn|Discuss earnings': { up: `How do my numbers look?`, _: `Walk me through the numbers` },
  'pick_incident|Ask about a recent incident': { _: `What do you know about the recent trouble?` },
  'pick_incident|Steer it somewhere else': { _: `Let’s talk about something else` },
  'intro|Introduce yourself': { _: `Walk over and say who you are` },
  'who|Ask who it was': { _: `Who did it?` },
  'who|Ask who he’s heard it was': { _: `Who’s saying it was?` },
};

export function speak(w: World, p: Character, t: Character, code: string, label: string): string {
  const key = code.split(':')[0];
  const reg = regOf(w, p, t);
  const ov = OVERRIDE[`${key}|${label}`];
  let s = ov;
  let m: RegExpMatchArray | null = null;
  if (!s) {
    if (key === 'earn' && t.bossId === p.id) s = { _: `How much did you bring in?` };
    else {
      const e = SPEAK[key];
      if (!e) return label;
      m = e.re ? label.match(e.re) : null;
      if (e.re && !m) return label; // the wording was not what was expected: leave it alone rather than guess
      s = e.to;
    }
  }
  const out = s[reg] ?? s._;
  if (!out) return label;
  return out.replace(/\$1/g, () => (m ? m[1] : '')).replace(/\{f\}/g, () => first(t));
}
