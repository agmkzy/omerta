const fill = (s: string, v: Record<string, string>) => s.replace(/\{(\w+)\}/g, (_, k) => v[k] ?? '');

// One line, in his voice and tone, for this situation. The line used is rotated per man so asking twice does not repeat it.
export function say(w: World, t: Character, p: Character, intent: string, vars: Record<string, string> = {}): string {
  const bank = BANK[intent];
  if (!bank) return '';
  const A = arch(t), T = toneOf(w, t, p);
  let pool: E[] = [], top = -1;
  for (const e of bank) {
    if (e.a && !e.a.includes(A)) continue;
    if (e.t && !e.t.includes(T)) continue;
    const sc = (e.a ? 2 : 0) + (e.t ? 1 : 0);
    if (sc > top) { top = sc; pool = [e]; } else if (sc === top) pool.push(e);
  }
  if (!pool.length) return '';
  const key = `say:${t.id}`;
  const n = p.cooldown[key] ?? 0;
  p.cooldown[key] = n + 1;
  return fill(pool[(hash(t.id + intent) + n) % pool.length].s, { N: t.name, ...vars });
}
export const hasBank = (intent: string) => intent in BANK;
export const BANKS = BANK;

