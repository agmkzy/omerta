// V77: how a man sounds, and how the player sounds to him.
//
// Nothing here is saved. A man's voice is worked out each time from what the game already holds about him (his traits, rank,
// and how he feels about the player), so the same man always sounds like himself and old saves need no change.
//
//   toneOf   how he feels about you right now: warm, easy, guarded, cold, hostile, or deferential (you outrank him)
//   regOf    how you would address him: up (he outranks you), down (he is your man), wary, easy, level
//   say      one line from a bank, in his voice and his tone, rotated so he does not repeat himself
//   speak    the player's own wording for an option, by who he is speaking to (the action, its cost and its hint are untouched)
import { arch, hash, Arch } from './voice';
import type { Character, World } from './types';

export type Tone = 'warm' | 'easy' | 'guarded' | 'cold' | 'hostile' | 'deferential';
export type Reg = 'up' | 'down' | 'wary' | 'easy' | 'level';

const RANKS = ['civilian', 'associate', 'soldier', 'capo', 'underboss', 'boss'];
export const rk = (c: Character) => RANKS.indexOf(c.rank);
export const first = (c: Character) => c.name.split(' ')[0];
export const surname = (c: Character) => c.name.split(' ').slice(1).join(' ') || c.name;

// Read without creating: asking how a man feels must never add a record to the save.
const feel = (a: Character, b: Character) => a.rels[b.id] ?? { trust: 0.1, respect: 0.3, affection: 0.1, grudge: 0, lastMet: -1e9 };

export function toneOf(w: World, t: Character, p: Character): Tone {
  const r = feel(t, p);
  if (r.grudge >= 0.35) return 'hostile';
  if (t.rank !== 'civilian' && rk(p) > rk(t) && !(r.trust >= 0.65)) return 'deferential';
  if (r.trust >= 0.65 || r.affection >= 0.65) return 'warm';
  if (r.trust >= 0.4 || r.affection >= 0.45) return 'easy';
  if (r.trust < 0.2 && r.affection < 0.3) return 'cold';
  return 'guarded';
}

export function regOf(w: World, p: Character, t: Character): Reg {
  const grudge = Math.max(feel(t, p).grudge, feel(p, t).grudge);
  if (grudge >= 0.25) return 'wary';
  if (t.bossId === p.id) return 'down';
  if (t.id === p.bossId || rk(t) > rk(p)) return 'up';
  const r = feel(t, p);
  if (r.trust >= 0.5 || r.affection >= 0.5) return 'easy';
  return 'level';
}

